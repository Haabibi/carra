 await page.getByRole('button',{name:'Close',exact:true}).click();
 await page.locator('#library-add').click();
 await page.locator('#library-file').setInputFiles({name:'receipt-photo.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jP1sAAAAASUVORK5CYII=','base64')});
 await page.getByText('Document saved to your library.').waitFor();
 await page.reload();
