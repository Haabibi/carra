 await page.locator('#library-search').fill('receipt-photo');
 assert.equal(await page.locator('.library-row').count(),1);
 await page.getByRole('button',{name:'Open',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.library-original-image')?.naturalWidth>0);
 await page.keyboard.press('Escape');
