import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  page.on('pageerror', error => { errors.push(error.message); console.error(error.message); });
  await page.goto('http://localhost:3011/#/analyze/new');
  await page.locator('#document-sample').waitFor();
  assert.equal(await page.locator('#document-sample option').count(), 60);
  await page.waitForFunction(() => document.querySelector('#document-preview-body canvas')?.width > 500);
  await page.locator('#document-preview-body .pdf-text summary').click();
  await page.waitForFunction(() => document.querySelector('#document-preview-body pre')?.textContent.includes('600.36'));
  await page.locator('#document-preview-body .pdf-text summary').click();
  await page.screenshot({ path: 'artifacts/pdf-input-desktop.png', fullPage: true });
  await page.locator('#document-sample').selectOption('service_record-22');
  await page.waitForFunction(() => document.querySelector('.pdf-position')?.textContent === 'Page 1 of 2');
  await page.getByRole('button', { name: 'Next PDF page' }).click();
  await page.waitForFunction(() => document.querySelector('.pdf-position')?.textContent === 'Page 2 of 2');
  await page.getByRole('button', { name: 'Zoom PDF in' }).click();
  await page.waitForFunction(() => document.querySelector('.pdf-zoom')?.textContent === '125%');
  await page.locator('#document-sample').selectOption('service_record-29');
  await page.getByRole('button', { name: 'Read document', exact: true }).click();
  await page.waitForURL(/\/review$/);
  assert.equal(await page.locator('.edit-item').first().locator('[name=status]').inputValue(), 'completed');
  assert.equal(await page.locator('.edit-item').first().locator('[name=labor]').inputValue(), '92.50');
  assert.equal(await page.locator('.edit-item').first().locator('[name=parts]').inputValue(), '');
  await page.waitForFunction(() => document.querySelector('#review-reference canvas')?.width > 0);
  await page.screenshot({ path: 'artifacts/pdf-review-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Looks right, explain it' }).click();
  await page.waitForURL(url => /\/analyze\/estimate-[a-z0-9-]+$/.test(url.hash));
  await page.getByRole('heading', { name: 'Work on this service record' }).waitFor();
  assert.match(await page.locator('#row-0').innerText(), /Completed/);
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#report-reference canvas')?.width > 0);
  await page.getByRole('link', { name: 'New estimate', exact: true }).click();
  await page.getByRole('button', { name: 'Use my estimate', exact: true }).click();
  await page.locator('#document-files').setInputFiles('data/carra-estimates/samples/29_ev_12v_dc_dc_estimate.pdf');
  await page.locator('.document-file').waitFor();
  await page.getByRole('button', { name: 'Read document', exact: true }).click();
  await page.waitForURL(/\/review$/);
  assert.equal(await page.locator('.edit-item').first().locator('[name=status]').inputValue(), 'authorized');
  await page.getByRole('link', { name: 'New estimate', exact: true }).click();
  await page.getByRole('button', { name: 'Use my estimate', exact: true }).click();
  await page.locator('#document-files').setInputFiles('design/carra-character/carra-agent.png');
  await page.locator('.document-file').waitFor();
  // Test missing-key UI without depending on a developer's configured key.
  await page.route('**/api/estimates/parse', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 'PARSER_NOT_CONFIGURED', error: 'AI document reading is not configured yet. Try a sample or enter the details manually.' }) }));
  await page.getByRole('button', { name: 'Read document', exact: true }).click();
  await page.locator('#document-error').filter({ hasText: 'not configured' }).waitFor();
  assert.equal(await page.locator('.document-file').count(), 1);
  await page.getByRole('button', { name: 'Enter details manually instead' }).click();
  await page.waitForURL(/\/review$/);
  assert.equal(await page.locator('[name=grandTotal]').inputValue(), '');
  await page.reload();
  await page.locator('#review-reference img').waitFor();
  await page.getByRole('link', { name: 'New estimate', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('#document-preview-body canvas')?.width > 0);
  await page.screenshot({ path: 'artifacts/pdf-input-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('Document UI passed: 60 original PDFs, multi-page navigation, zoom, completed/authorized status, exact costs, PDF upload, review/report refresh, photo fallback, and mobile layout.');
} finally { await browser.close(); }
