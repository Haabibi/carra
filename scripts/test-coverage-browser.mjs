import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto((process.env.CARRA_TEST_URL || 'http://localhost:3011') + '/#/analyze/new');
  await page.locator('#document-sample').selectOption('service_record-29');
  await page.getByRole('button', { name: 'Read document', exact: true }).click();
  await page.waitForURL(/\/review$/);
  await page.getByRole('button', { name: 'Looks right, explain it' }).click();
  await page.locator('#item-list').waitFor();
  assert.equal(await page.locator('#coverage').count(), 0);
  assert.equal(await page.locator('.item-title .coverage-warranty').count(), 2);
  assert.equal(await page.locator('.item-title .coverage-excluded').count(), 1);
  await page.locator('#row-0').click();
  const details = page.locator('#detail-0 .item-coverage');
  await details.locator('summary').click();
  assert.match(await details.innerText(), /Carra Care/);
  assert.match(await details.innerText(), /Already paid/);
  assert.equal(await details.locator('a').getAttribute('href'), '#/my');
  await page.locator('#item-list').screenshot({ path: 'artifacts/protection-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await page.locator('#row-0').click();
  const sheet = page.locator('#item-sheet');
  await sheet.locator('.item-coverage summary').click();
  assert.match(await sheet.locator('.item-coverage').innerText(), /authorized service center/);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal overflow');
  await sheet.screenshot({ path: 'artifacts/protection-mobile.png' });
  await page.evaluate(() => CarraProfile.save({ ...CarraProfile.get(), warranty: '' }));
  await page.reload();
  await page.locator('#item-list').waitFor();
  assert.equal(await page.locator('.item-title .coverage-warranty').count(), 0);
  assert.equal(await page.locator('.item-title .coverage-unknown').count(), 2);
  assert.deepEqual(errors, []);
  console.log('Compact coverage passed: real sample badges, exclusions, expandable next step, plan link, mobile sheet.');
} finally { await browser.close(); }
